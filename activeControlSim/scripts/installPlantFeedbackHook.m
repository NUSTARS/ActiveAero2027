function installPlantFeedbackHook(buildDir)
%INSTALLPLANTFEEDBACKHOOK Insert a controller boundary into exported plant C.
% Raw Simulink code/cache is never modified. Fail if the generated boundary
% changes rather than silently adding an incorrect extra sample of feedback.
sourceFile = fullfile(buildDir, 'toIDE', 'Src', 'autocodePlant.c');
headerFile = fullfile(buildDir, 'toIDE', 'Inc', 'autocodePlant_feedback.h');
code = fileread(sourceFile);
marker = '/* STM32_CURRENT_SAMPLE_FEEDBACK */';
header = strjoin({ ...
    '#ifndef AUTOCODEPLANT_FEEDBACK_H', ...
    '#define AUTOCODEPLANT_FEEDBACK_H', ...
    '#include "autocodePlant.h"', ...
    '/* Called once per major step, after outputs and before state updates.', ...
    ' * Return false to sample the final endpoint without advancing states. */', ...
    'typedef boolean_T (*autocodePlant_FeedbackCallback)(sensor_bus *, plant_bus *, real_T [4]);', ...
    'void autocodePlant_SetFeedbackCallback(autocodePlant_FeedbackCallback callback);', ...
    '#endif', ''}, newline);
if ~contains(code, marker)
    % Generated local names (for example idxDelay versus i) change with
    % model edits and code-generation optimizations. Identify the top-level
    % major-step block containing discrete updates instead. Matching its
    % closing brace at the same indentation excludes nested output updates
    % and the separate solver/time-advance block.
    boundary = ['(?m)^  if \(rtmIsMajorTimeStep\(autocodePlant_M\)\) \{\r?\n' ...
        '[\s\S]*?^  \}'];
    [starts, ~, blocks] = regexp(code, boundary, 'start', 'end', 'match');
    starts = starts(contains(blocks, '/* Update for '));
    assert(numel(starts) == 1, ...
        'Expected one plant output/update boundary in %s; found %d.', ...
        sourceFile, numel(starts));
    hook = strjoin({ ...
        marker, ...
        '  if (rtmIsMajorTimeStep(autocodePlant_M) && autocodePlant_feedback != NULL) {', ...
        '    if (!autocodePlant_feedback(autocodePlant_Y_sensor_bus_i,', ...
        '                                autocodePlant_Y_plant_bus_e,', ...
        '                                autocodePlant_U_control_deg)) return;', ...
        '  }', '', ''}, newline);
    code = [code(1:starts-1) hook code(starts:end)];
    declarations = strjoin({ ...
        '#include "autocodePlant_feedback.h"', ...
        '#include <stddef.h>', ...
        'static autocodePlant_FeedbackCallback autocodePlant_feedback;', ...
        'void autocodePlant_SetFeedbackCallback(autocodePlant_FeedbackCallback callback)', ...
        '{', ...
        '  autocodePlant_feedback = callback;', ...
        '}', '', ''}, newline);
    code = [declarations code];
end
writeHookFile(sourceFile, code);
writeHookFile(headerFile, header);
fprintf('Installed current-sample plant/controller feedback boundary.\n');
end
function writeHookFile(path, text)
fid = fopen(path, 'w');
assert(fid >= 0, 'Cannot write %s.', path);
closer = onCleanup(@() fclose(fid));
fwrite(fid, text, 'char');
end
