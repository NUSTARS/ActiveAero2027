function testGeneratedGyroUsesRadiansPerSecond(testCase)
    compiler = mex.getCompilerConfigurations('C', 'Selected');
    assumeTrue(testCase, ~isempty(compiler), ...
        'A configured C compiler is required for this generated-C behavior test.');

    modelsDir = fileparts(fileparts(mfilename('fullpath')));
    projectRoot = fileparts(modelsDir);
    generatedPath = fullfile(projectRoot, 'build_autocodeModel', ...
        'toIDE', 'Src', 'autocodeModel_initialize.c');
    source = fileread(generatedPath);
    helper = regexp(source, ...
        'void autocodeModel_initializeSensorBus[\s\S]*?\n}\n(?=\nvoid autocodeModel_oneStep)', ...
        'match', 'once');
    verifyNotEmpty(testCase, helper);

    tempDir = tempname;
    mkdir(tempDir);
    cleanup = onCleanup(@() cleanupMexSmoke(tempDir)); %#ok<NASGU>
    prefix = sprintf([ ...
        '#include "mex.h"\n#include <stddef.h>\n' ...
        'typedef double real_T;\n' ...
        'typedef struct { real_T x, y, z; } Vector3f_t;\n' ...
        'typedef struct { real_T gyroBiasTrue_rps[3]; real_T accBiasTrue_mps2[3]; } truth_bus_t;\n' ...
        'typedef struct { truth_bus_t truth_bus; real_T fBdyMeas_mps2[3]; ' ...
        'real_T wBdyMeas_rps[3]; real_T magBdyMeas_nT[3]; real_T baroMeas_Pa; } sensor_bus;\n']);
    suffix = sprintf([ ...
        '\nvoid mexFunction(int nlhs, mxArray *plhs[], int nrhs, const mxArray *prhs[]) {\n' ...
        '  sensor_bus bus = {0}; Vector3f_t accel = {1,2,3}; Vector3f_t gyro = {180,-90,45};\n' ...
        '  autocodeModel_initializeSensorBus(&bus, &accel, &gyro, NULL, 101325);\n' ...
        '  plhs[0] = mxCreateDoubleMatrix(1, 3, mxREAL); double *out = mxGetPr(plhs[0]);\n' ...
        '  for (int i = 0; i < 3; ++i) out[i] = bus.wBdyMeas_rps[i];\n}\n']);
    cFile = fullfile(tempDir, 'gyro_conversion_smoke.c');
    fid = fopen(cFile, 'w');
    fwrite(fid, [prefix helper suffix], 'char');
    fclose(fid);

    mex('-outdir', tempDir, cFile);
    addpath(tempDir);
    actual = gyro_conversion_smoke();
    verifyEqual(testCase, actual, [pi, -pi/2, pi/4], 'AbsTol', 1e-12);
end


function cleanupMexSmoke(tempDir)
    clear gyro_conversion_smoke;
    if any(strcmp(strsplit(path, pathsep), tempDir))
        rmpath(tempDir);
    end
    if isfolder(tempDir)
        rmdir(tempDir, 's');
    end
end


function writeText(path, text)
    fid = fopen(path, 'w');
    if fid < 0
        error('Cannot write test fixture: %s', path);
    end
    cleanup = onCleanup(@() fclose(fid));
    fwrite(fid, text, 'char');
end
